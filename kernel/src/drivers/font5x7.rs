//! A compact 5x7 bitmap font — Month 3, drivers.
//!
//! Each glyph is 7 bytes, one byte per row (top to bottom). Within a row byte,
//! bit `col` (0 = leftmost, 0..GLYPH_W) marks that column; higher bits are
//! unused. Covers printable ASCII 0x20..0x7E. Pure data + accessors, so it is
//! host-testable alongside the framebuffer text renderers.
//!
//! Derived from the classic public-domain "font8x8"-style 5x7 bitmap (the row
//! bits are the horizontal pixels). Some glyphs are simplified to fit 5 columns.

/// Bitmap width in pixels per glyph.
pub const GLYPH_W: usize = 5;
/// Bitmap height (rows) per glyph.
pub const GLYPH_H: usize = 7;
/// First indexed character.
const FIRST: u8 = 0x20;
/// Count of glyphs (0x20..=0x7E inclusive).
pub const GLYPH_COUNT: usize = 0x7F - 0x20;

