/// Look up the 5x7 glyph for a printable ASCII char. Non-printables map to '?'.
pub fn glyph(c: char) -> &'static [u8; GLYPH_H] {
    let code = c as u8;
    if code < FIRST || code >= FIRST + GLYPH_COUNT as u8 {
        &FONT5X7['?' as usize - FIRST as usize]
    } else {
        &FONT5X7[code as usize - FIRST as usize]
    }
}

/// True when every row byte uses only the low `GLYPH_H` bits (data sanity).
pub fn glyph_height_valid() -> bool {
    FONT5X7.iter().all(|g| g.iter().all(|&col| col < (1 << GLYPH_H)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn font_has_correct_shape() {
        assert_eq!(GLYPH_COUNT, 0x5F); // 0x20..=0x7E
        assert_eq!(FONT5X7.len(), GLYPH_COUNT);
        assert!(glyph_height_valid());
    }

    #[test]
    fn lowercase_and_uppercase_present() {
        for ch in ['a', 'A', '0', ' ', 'z', 'Z'] {
            let g = glyph(ch);
            assert_eq!(g.len(), GLYPH_H);
        }
    }

    #[test]
    fn unknown_char_falls_back_to_question_mark() {
        assert_eq!(glyph('\n'), glyph('?'));
    }
}